// pnpm gen:api               specs from the farm-backend main branch on GitHub
// pnpm gen:api v0.2.0        specs from a farm-backend tag or branch
// pnpm gen:api --local ../farm-backend/contracts/openapi
// Writes contracts/<service>.json (kept, Prism reads them) and src/api/generated/<service>.d.ts.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SERVICES = ['identity', 'catalog', 'land', 'media', 'order', 'logistics', 'notification']
const REPO = 'lakshayg2005/farm-backend'
const args = process.argv.slice(2)
const localAt = args.indexOf('--local')
const localDir = localAt >= 0 ? args[localAt + 1] : null
const ref = args.find((a) => !a.startsWith('--') && a !== localDir) ?? 'main'

mkdirSync('contracts', { recursive: true })
mkdirSync('src/api/generated', { recursive: true })

for (const service of SERVICES) {
  let text
  if (localDir) {
    try {
      text = readFileSync(join(localDir, `${service}.json`), 'utf8')
    } catch {
      console.warn(`skip ${service}: not in ${localDir}`)
      continue
    }
  } else {
    const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${ref}/contracts/openapi/${service}.json`)
    if (!res.ok) {
      console.warn(`skip ${service}: not in ${REPO}@${ref} (${res.status})`)
      continue
    }
    text = await res.text()
  }
  JSON.parse(text) // fail early on a bad file
  writeFileSync(join('contracts', `${service}.json`), text.endsWith('\n') ? text : `${text}\n`)
  execFileSync('pnpm', ['exec', 'openapi-typescript', join('contracts', `${service}.json`), '-o', join('src/api/generated', `${service}.d.ts`)], {
    stdio: 'inherit',
    shell: true,
  })
}

const generated = readdirSync('src/api/generated').filter((f) => f.endsWith('.d.ts'))
const lines = generated.map((f) => {
  const name = f.replace('.d.ts', '')
  const alias = name[0].toUpperCase() + name.slice(1)
  return `export type { components as ${alias}Components, paths as ${alias}Paths } from './${name}'`
})
writeFileSync('src/api/generated/index.ts', `// Generated by scripts/gen-api.mjs. Do not edit.\n${lines.join('\n')}\n`)
console.log(`Done: ${generated.length} services`)
